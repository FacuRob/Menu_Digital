const DICTS: Record<Lang, Dict> = { es, en, pt };

const detectLang = (): Lang => {
  const saved = localStorage.getItem("admin_lang");
  if (saved && saved in DICTS) return saved as Lang;
  const nav = (navigator.language || "es").slice(0, 2).toLowerCase();
  return (nav in DICTS ? nav : "es") as Lang;
};

interface I18nContextType {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

export const LanguageProvider = ({ children }: { children: ReactNode }) => {
  const [lang, setLangState] = useState<Lang>(detectLang);

  const setLang = useCallback((l: Lang) => {
    localStorage.setItem("admin_lang", l);
    setLangState(l);
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      let s = DICTS[lang][key] ?? DICTS.es[key] ?? key;
      if (vars) for (const k in vars) s = s.replace(`{${k}}`, String(vars[k]));
      return s;
    },
    [lang],
  );

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useLang = () => {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useLang debe usarse dentro de LanguageProvider");
  return ctx;
};

// ── Selector de idioma (desplegable compacto para el topbar) ──
// variant "hp": pastilla del mundo "Hora pico" (pantalla de acceso).
export function LangSelector({ isDark = false, variant }: { isDark?: boolean; variant?: "hp" }) {
  const { lang, setLang } = useLang();
  const current = LANGS.find((l) => l.code === lang) || LANGS[0];
  const hp = variant === "hp";
  return (
    <label
      style={{
        display: "inline-flex",
        alignItems: "center",
        gap: 5,
        position: "relative",
        cursor: "pointer",
      }}
      title="Idioma / Language"
    >
      {!hp && (
        <span aria-hidden style={{ fontSize: 15, lineHeight: 1 }}>
          {current.flag}
        </span>
      )}
      <select
        value={lang}
        onChange={(e) => setLang(e.target.value as Lang)}
        aria-label="Idioma"
        style={
          hp
            ? {
                appearance: "none",
                WebkitAppearance: "none",
                border: "2px solid #111216",
                background: "transparent",
                color: "#111216",
                borderRadius: 999,
                minHeight: 44,
                padding: "0 34px 0 16px",
                fontSize: 15,
                fontWeight: 700,
                fontFamily: "inherit",
                cursor: "pointer",
              }
            : {
                appearance: "none",
                WebkitAppearance: "none",
                border: `1px solid ${isDark ? "rgba(255,255,255,0.1)" : "rgba(0,0,0,0.1)"}`,
                background: isDark ? "#0f1117" : "#f8f9fa",
                color: isDark ? "#f1f5f9" : "#1e293b",
                borderRadius: 8,
                padding: "5px 24px 5px 8px",
                fontSize: 12.5,
                fontWeight: 600,
                fontFamily: "inherit",
                cursor: "pointer",
              }
        }
      >
        {LANGS.map((l) => (
          <option key={l.code} value={l.code} style={{ color: "#1e293b" }}>
            {l.label}
          </option>
        ))}
      </select>
      <svg
        width={11}
        height={11}
        viewBox="0 0 24 24"
        fill="none"
        stroke={hp ? "#111216" : isDark ? "#94a3b8" : "#64748b"}
        strokeWidth={2.4}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden
        style={{ position: "absolute", right: hp ? 14 : 8, pointerEvents: "none" }}
      >
        <path d="M6 9l6 6 6-6" />
      </svg>
    </label>
  );
}
